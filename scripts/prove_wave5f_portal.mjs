// Wave 5 Track F — dispatch, the token-only vendor portal, split awards, PDF.
//
//   node scripts/prove_wave5f_portal.mjs
//
// Requires: Postgres 55432, the API on 33001, the web on 33002.
//
// WHAT IS ACTUALLY BEING PROVEN
//   The feature list is long, so the harness is organised around the six claims
//   that would each be a real defect if false:
//
//   1. SMART LINE SPLITTING. A held line and a store-fulfilled line must not
//      reach a vendor, and what IS sent is the PENDING quantity. Proven by
//      building a PR with all three line kinds, issuing an RFQ, and reading the
//      pack back — not by reading the query.
//
//   2. TIME-BOUND TOKENS. A dispatch mints a link; a link past its expiry is
//      refused. The token is compared by SHA-256, so the raw value is not in the
//      database — proved by searching the column for it.
//
//   3. THE PORTAL IS A SANDBOX. The token sees only its own lines. Proven by
//      holding two tokens for two vendors and showing each cannot see the
//      other's lines or the PR.
//
//   4. THE EXCEL ROUND TRIP. A template generated by the server is parsed back
//      by the server and submitted. The file is a real ZIP/OOXML package, proved
//      by its magic bytes — not a renamed CSV.
//
//   5. REVISIONS DO NOT ERASE. Submit, submit again, and show v1 still readable
//      with its own price while v2 is live.
//
//   6. SPLIT AWARDS AND OFFLINE NEGOTIATION. One line, two different winners in
//      two rounds, with the first award still on record; and a phone-negotiated
//      rate that appends a version and lands in the immutable trail.
//
// EVERY MUTATION IS RESTORED IN `finally`. Audit rows cannot be restored — that
// is rule 5 working — and the count is reported rather than hidden.

