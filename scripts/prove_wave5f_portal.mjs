/**
 * Fill the downloaded template the way a vendor would, and hand back the bytes.
 *
 * It parses the template with the API's OWN reader and re-emits it with the API's
 * OWN writer, so the round trip exercises the same code the upload endpoint uses
 * rather than a second implementation that might agree with itself. An earlier
 * version of this function returned null and the upload check was therefore
 * never reached — a silently skipped test that read like a passing one.
 */
async function fillTemplate(tplBuf) {
  const { readXlsx, buildXlsx } = await import(
    new URL('../apps/api/dist/vendor-portal/xlsx.js', import.meta.url).href
  );

  const sheet = readXlsx(tplBuf);
  const headIdx = sheet.rows.findIndex((r) => r.some((c) => String(c ?? '').trim().toLowerCase() === 'line'));
  if (headIdx < 0) return null;
  const head = sheet.rows[headIdx];
  const iLine = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'line');
  const iPrice = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'unit price');
  const iLead = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'lead time (days)');
  const iWarr = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'warranty (months)');
  const iTerms = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'payment terms');
  const iValid = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'validity (days)');
  const iTax = head.findIndex((c) => String(c ?? '').trim().toLowerCase() === 'taxes included');
  if (iLine < 0 || iPrice < 0) return null;

  // The commercial terms are filled in as well as the price. Without them the
  // comparative matrix's lead-time and payment-terms columns stay NULL and the
  // F7 proof degrades into "the columns exist but nothing can populate them".
  // Columns are matched by header name and skipped when the template lacks them,
  // so this does not assume a fixed column order.
  const put = (copy, idx, value) => { if (idx >= 0) copy[idx] = value; };

  // Price only the real lines — the trailing note rows have no line number.
  let price = 500;
  const rows = sheet.rows.map((r, ri) => {
    if (ri <= headIdx) return r;
    const n = Number(r[iLine]);
    if (!Number.isFinite(n) || n <= 0) return r;
    const copy = [...r];
    put(copy, iPrice, price);
    put(copy, iLead, 14);
    put(copy, iWarr, 12);
    put(copy, iTerms, '30 days from invoice');
    put(copy, iValid, 45);
    put(copy, iTax, 'Yes');
    price += 100;
    return copy;
  });

  return buildXlsx({ name: 'Quotation', rows });
}
